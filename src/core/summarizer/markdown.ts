import fs from "fs/promises";
import path from "path";
import type { CodeGraph, GraphNode } from "../graph/index.js";

function formatDate(iso: string): string {
  return iso.slice(0, 10);
}

function truncate(s: string | undefined, max: number): string {
  if (!s) return "—";
  return s.length > max ? s.slice(0, max - 1) + "…" : s;
}

function getNodeTypeLabel(type: string): string {
  const map: Record<string, string> = {
    file: "File",
    class: "Class",
    function: "Function",
    module: "Module",
  };
  return map[type] ?? type;
}

interface FolderData {
  folder: string;
  files: GraphNode[];
  allNodes: GraphNode[];
}

function groupByFolder(graph: CodeGraph): Map<string, FolderData> {
  const map = new Map<string, FolderData>();
  const nodes = graph.nodes();

  for (const node of nodes) {
    if (node.type !== "file" || !node.path) continue;

    const folder = path.dirname(node.path) || ".";

    if (!map.has(folder)) {
      map.set(folder, { folder, files: [], allNodes: [] });
    }

    map.get(folder)!.files.push(node);
  }

  // Add non-file nodes to their parent folder
  for (const node of nodes) {
    if (node.type === "file") continue;
    const folder = path.dirname(node.path || node.id) || ".";
    if (map.has(folder)) {
      map.get(folder)!.allNodes.push(node);
    }
  }

  return map;
}

function buildFolderMarkdown(data: FolderData, graph: CodeGraph): string {
  const { folder, files } = data;
  const now = new Date().toISOString();
  const nodeCount = files.length + data.allNodes.length;

  const lines: string[] = [];

  lines.push(`# 📁 ${folder} — Summary`);
  lines.push(`> Auto-generated by codeknowledge. Do not edit manually.`);
  lines.push(`> Last updated: ${formatDate(now)} | ${files.length} files | ${nodeCount} nodes`);
  lines.push(``);

  // Collect all folder summaries for purpose section
  const summaries = files
    .filter((f) => f.summary)
    .map((f) => f.summary!)
    .join(" ");

  if (summaries) {
    lines.push(`## Purpose`);
    lines.push(truncate(summaries, 400));
    lines.push(``);
  }

  // Files table
  lines.push(`## Files`);
  lines.push(`| File | Type | Summary |`);
  lines.push(`|------|------|---------|`);

  for (const file of files) {
    const name = path.basename(file.path);
    const summary = truncate(file.summary, 100);
    lines.push(`| ${name} | File | ${summary} |`);
  }
  lines.push(``);

  // Key exports
  const allExports = files.flatMap((f) => f.exports ?? []).filter(Boolean);
  if (allExports.length > 0) {
    lines.push(`## Key Exports`);
    for (const file of files) {
      if (file.exports && file.exports.length > 0) {
        lines.push(`- \`${path.basename(file.path)}\` — ${file.exports.slice(0, 6).join(", ")}`);
      }
    }
    lines.push(``);
  }

  // Dependencies
  const deps = new Set<string>();
  const usedBy = new Set<string>();

  for (const file of files) {
    for (const dep of graph.successors(file.id)) {
      if (dep.type === "file" && dep.path && path.dirname(dep.path) !== folder) {
        deps.add(dep.path);
      }
    }
    for (const user of graph.predecessors(file.id)) {
      if (user.type === "file" && user.path && path.dirname(user.path) !== folder) {
        usedBy.add(user.path);
      }
    }
  }

  if (deps.size > 0 || usedBy.size > 0) {
    lines.push(`## Dependencies`);
    if (deps.size > 0) {
      lines.push(`- **Depends on:** ${[...deps].slice(0, 5).map((d) => `\`${d}\``).join(", ")}`);
    }
    if (usedBy.size > 0) {
      lines.push(`- **Used by:** ${[...usedBy].slice(0, 5).map((d) => `\`${d}\``).join(", ")}`);
    }
    lines.push(``);
  }

  return lines.join("\n");
}

export async function generateAllMarkdown(
  graph: CodeGraph,
  outputDir: string,
  rootDir: string
): Promise<void> {
  const folderMap = groupByFolder(graph);

  for (const [folder, data] of folderMap) {
    if (data.files.length === 0) continue;

    const content = buildFolderMarkdown(data, graph);
    const summaryDir = path.join(outputDir, folder);
    await fs.mkdir(summaryDir, { recursive: true });

    const summaryPath = path.join(summaryDir, "SUMMARY.md");
    await fs.writeFile(summaryPath, content, "utf8");
  }
}
